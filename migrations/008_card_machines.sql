-- Maquinas de cartao e taxas por bandeira/parcela. Taxa e gravada em cada pagamento (fee_rate/fee_amount) no momento da venda.
CREATE TABLE card_machines (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(60) NOT NULL,
  active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE card_rates (
  machine_id INT UNSIGNED NOT NULL,
  brand VARCHAR(8) NOT NULL,
  kind VARCHAR(8) NOT NULL,
  installments TINYINT UNSIGNED NOT NULL DEFAULT 1,
  rate DECIMAL(5,2) NOT NULL,
  PRIMARY KEY (machine_id, brand, kind, installments),
  CONSTRAINT fk_rates_machine FOREIGN KEY (machine_id) REFERENCES card_machines(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
